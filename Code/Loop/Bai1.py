"""
    1. In ra lần lượt các số từ 1 đến 10
"""

""" Vòng lặp for có:
        Tham số 1: i = 1
        Tham số 2: i < 10
        Tham số 3: i + 1
"""
print("Dùng for")
for i in range(1, 10, 1):
    print(f"{i}")

""" Vòng lặp while có:
        Tham số 1: i = 1
        Tham số 2: i < 10
        Tham số 3: i + 1
"""
print("Dùng while")
i = 1
while i < 10:
    print(f"{i}")
    i += 1